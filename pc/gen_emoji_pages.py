def graphemes(s):
    """Split a run of emoji into single emoji: base + FE0F / skin / ZWJ continuations."""
    out = []
    for ch in s:
        cp = ord(ch)
        if out and (cp in (0xFE0F, 0x200D, 0x20E3) or out[-1].endswith("‍")):
            out[-1] += ch
        else:
            out.append(ch)
    return out


def twemoji_name(e):
    cps = [ord(c) for c in e]
    full = "-".join(f"{c:x}" for c in cps)
    if (TWEMOJI / f"{full}.png").exists():
        return full
    short = "-".join(f"{c:x}" for c in cps if c != 0xFE0F)
    return short if (TWEMOJI / f"{short}.png").exists() else None


def c_str(s):
    out, after_hex = "", False
    for c in s:
        if ord(c) < 0x80 and c not in '"\\':
            out += ('""' if after_hex and c in "0123456789abcdefABCDEF" else "") + c   # end the \x escape
            after_hex = False
        else:
            out += "".join(f"\\x{b:02x}" for b in c.encode())
            after_hex = True
    return '"' + out + '"'


def pages(verbose=False):
    """[(tab emoji, title, the page's ROWS * COLS emoji)], every one with a Twemoji image."""
    out = []
    for tab, name, run in PAGES:
        em, seen = [], set()
        for e in graphemes(run):
            if e in seen:
                continue
            if not twemoji_name(e):
                if verbose:
                    print(f"  {name}: no Twemoji image for {e!r} ({' '.join(f'{ord(c):x}' for c in e)}), skipped")
                continue
            seen.add(e)
            em.append(e)
        assert twemoji_name(tab), tab
        if len(em) < ROWS * COLS:
            raise SystemExit(f"{name}: only {len(em)} emoji, need {ROWS * COLS}")
        if verbose:
            print(f"{name}: {len(em)} emoji, using {ROWS * COLS}")
        out.append((tab, name, em[:ROWS * COLS]))
    return out


def keyboard_emoji():
    """Every emoji the keyboard shows (pc/export_chat.py puts them in the big font too)."""
    return sorted({e for tab, _, em in pages() for e in [tab, *em]})


